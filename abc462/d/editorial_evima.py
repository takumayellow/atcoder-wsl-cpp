#
# 出典: https://atcoder.jp/contests/abc462/editorial/21022 （by evima）
# コード本体は公式のまま（変数名 M, d, c, ans もそのまま）。コメントのみ追加。
#
# 【考え方】
#   犯行開始時刻 t を主役にする。時刻 t に「犯行 t..t+D の間ずっと居られる人数」を
#   c_t とすると、その t で成立する共犯ペアは C(c_t, 2) = c_t(c_t-1)/2。
#   答えは全時刻の和 Σ_t C(c_t, 2)。
#
#   人 i が t..t+D に居られる条件は S_i ≤ t かつ t+D ≤ T_i、すなわち
#       S_i ≤ t ≤ T_i − D
#   つまり退室時刻を「T_i − D」と読み替えれば、各人は区間 [S_i, T_i − D] に +1 する。
#   この区間加算を imos法（差分配列 d → 累積和）で O(N + M) に。
#
# 【計算量】O(N + M)、M = 10^6 + 1。
# ===========================================================================

N, D = map(int, input().split())      # N: 容疑者数, D: 犯行の長さ
M = 10**6 + 1                          # 開始時刻 t の上限+1（T_i ≤ 10^6 なので t も高々 10^6）
d = [0] * M                            # imos の差分配列（最後に累積和して人数 c_t になる）

for i in range(N):
    S, T = map(int, input().split())   # 人 i の入室 S, 退室 T
    if T - S >= D:                     # 区間が D 以上ないと、その人は誰とも組めない（飛ばす）
        d[S] += 1                      # 開始時刻 t = S から +1
        d[T - D + 1] -= 1              # t = (T - D) + 1 で +1 を打ち消す → [S, T-D] に +1

c, ans = 0, 0
for i in range(M):
    c += d[i]                          # ここまでの累積 = c_t（時刻 i に居合わせられる人数）
    ans += c * (c - 1) // 2            # その時刻のペア数 C(c, 2) を加算
print(ans)
