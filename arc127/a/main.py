# ARC127 A - Leading 1s (300点)
# https://atcoder.jp/contests/arc127/tasks/arc127_a
#
# 解法: 「先頭が 1 の k 連続」で数え上げ（寄与の分解） O(D^2), D = 桁数 <= 16
#   f(x) = x の先頭から連続する 1 の個数。求めるのは f(1)+...+f(N)。
#   f(x) = Σ_{k>=1} [x の先頭 k 桁がすべて 1] と分解し、k ごとに個数を数える。
#   詳しい考察は同ディレクトリの explanation.md を参照。

n = int(input())
head = ans = 0

# head = 1, 11, 111, ... (レピュニット)。これが「先頭 k 桁がすべて 1」の k 桁分の接頭辞。
# N <= 10^15 は高々 16 桁なので、k は 16 まで見れば十分。
for _ in range(16):

  head = head * 10 + 1        # 1 -> 11 -> 111 -> ... と 1 を末尾に足していく

  L = head                    # i = 0 のときのブロック先頭。以降 L = head * 10^i

  # 「先頭が head で、そのあとに i 桁が続く数」= 区間 [L, L + 10^i - 1] （ちょうど 10^i 個）
  # i を増やすと L は 10 倍ずつ大きくなるので、n を超えたらそれ以降も超える。
  for i in range(16):

    # ★必須のガード★ L > n だと下の else が n - L + 1 <= 0 を足してしまい、
    # 答えが負の方向に壊れる（このガードを外すと N=1 で -1234567901234542 になる）。
    if L > n:
      break

    R = L + 10 ** i           # ブロックの「終端の次」。ブロックは [L, R-1]

    if R <= n + 1:            # R - 1 <= n、つまりブロックが丸ごと N 以下に収まる
      ans += R - L            # = 10^i 個ぶん加算

    else:                     # ブロックの途中で n に到達 → 入るのは [L, n] の分だけ
      ans += n - L + 1
      break                   # i を増やすと L はさらに大きくなるので、以降は 0 個

    L *= 10                   # 次は桁を 1 つ増やしたブロック

print(ans)
