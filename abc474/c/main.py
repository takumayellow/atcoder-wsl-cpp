# 【問題（このコードから読み取れる仕様）】
#   長さ N の順列 P が「1列に並んだ人の列」として与えられる。
#   クエリが Q 個あり、各クエリで整数 x が与えられる。
#   → 人 x を列から抜き取り、列の最後尾に付け直す。
#   全クエリを処理したあとの列を出力する。
#
# 【このファイルの位置づけ】
#   やっていることは仕様そのままで、答えは必ず合う。
#   （src.py とランダム 300 ケースで出力完全一致を確認済み）
#   しかし list.remove() が遅く、N=Q=2*10^5 で実測 9.43 秒 → TLE。
#   高速版は src.py を参照。壊れている初期案は sub.py を参照。
#
# 【計算量】 O(N * Q)  … 最悪 2*10^5 * 2*10^5 = 4*10^10 相当の要素移動
# 【メモリ】 O(N)
# =============================================================================

# 1行目: N（人数 = 列の長さ）と Q（クエリ数）
#   input()        → "5 3" のような1行の文字列を読む
#   .split()       → ["5", "3"] に分割
#   map(int, ...)  → 各要素を int に変換（遅延評価の map オブジェクト）
#   n, q = ...     → 2要素にアンパックして代入
n, q = map(int, input().split())

# 2行目: 初期の並び P。p[0] が先頭（列の一番前）、p[-1] が最後尾。
#   ここは list() で確定させる（あとで remove / append するのでリストが必要）。
#   ※ p の中身は 1..n の順列なので「値の重複は無い」。
#     この事実が remove(a) を「1個だけ消す」操作として正当化している。
p = list(map(int,input().split()))

# クエリを Q 回処理する。i 自体はループ内で使わないので、
# 本来は for _ in range(q) と書くのが Python の慣習。
for i in range(q):
    # 3行目以降: 移動させたい人の番号 x（このコードでは変数名 a）
    a = int(input())

    # --- ここが全体のボトルネック -------------------------------------------
    # list.remove(a) は内部で2段階のことをやっている:
    #   (1) 先頭から順に走査して a と等しい最初の要素の位置を探す  … O(N)
    #   (2) 見つけた位置より後ろの要素を、全部1つずつ前に詰める（memmove）… O(N)
    # つまり1回あたり O(N)。これを Q 回まわすので O(N*Q) になる。
    #
    # 特に「常に先頭の人が呼ばれる」入力（1,2,3,... の順にクエリが来る）だと
    # 毎回 N 要素まるごと詰め直すことになり、最悪ケースを踏む。
    #
    # なお a が list に無い場合 remove は ValueError を投げるが、
    # ここでは直後に append で戻しているため、同じ x が何度来ても
    # 「必ず1個だけ存在する」状態が保たれ、例外にはならない。
    #   （この不変条件を壊しているのが sub.py のバグ。）
    p.remove(a)

    # 最後尾へ付け直す。list.append は償却 O(1) なのでここは軽い。
    p.append(a)
    # -------------------------------------------------------------------------

# 出力: 空白区切りで1行に並べる。
#   print(*p) は print(p[0], p[1], ..., p[-1]) と同じで、
#   区切り文字は既定の半角スペース。
# ※ src.py は「1行1個（改行区切り）」で出力しており、この2つは形式が食い違う。
#   どちらが正かは問題文の出力形式に従うこと（AtCoder の標準ジャッジは改行位置も見る）。
print(*p)
