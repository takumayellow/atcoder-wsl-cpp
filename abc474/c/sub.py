# 【狙い】
#   「抜かれた人はどうせ後ろに集まるのだから、抜いた順に別リスト l へ貯めて、
#     最後に (残った列) + (抜かれた列) と連結すれば1回のループで済む」
#   という発想。remove を毎回やる点は main.py と同じだが、append を省いて
