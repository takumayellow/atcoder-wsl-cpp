# N（人数）と Q（クエリ数）
n, q = map(int,input().split())

# 初期の並び。p[0] が先頭、p[-1] が最後尾。
p = list(map(int,input().split()))

# 「抜かれた人」を抜かれた順に貯めるバッファ。
# ここが設計ミスの本体 ―― 重複を許すリストなので (B) の原因になる。
l = []

for i in range(q):
    # 移動対象の人 a
    a = int(input())

    # まずバッファへ積む。
    # ※ a が既に l に入っていても気付かずもう1個積んでしまう（→ 重複 (B)）。
    l.append(a)

    # 列 p から抜く。
    # ★ ここで落ちる ★
    #   2回目以降の同じ a に対して、p にはもう a が居ないので ValueError。
    #   main.py はこの直後に p.append(a) で戻していたため
    #   「p には常に全員が1個ずつ居る」という不変条件が保たれていた。
    #   その1行を省いた結果、不変条件が壊れている。
    p.remove(a)

# 「残った列」+「抜かれた列」を連結して出力するつもりだった。
# 発想自体は悪くなく、l から重複を除いて「各人の最後の出現順」だけを残せば
# 正しい答えになる。（＝ dict の挿入順を使う解法と同じ考え方）
#
# 例えば以下のように直せば正しくなる（ただし remove が O(N) なので TLE は残る）:
#   from collections import OrderedDict
#   ...
#   od = OrderedDict()
#   for _ in range(q):
#       a = int(input())
#       if a in od: od.move_to_end(a)   # 既出なら順番だけ後ろへ
#       else:       od[a] = None; p.remove(a)
#   print(*(p + list(od)))
print(*(p+l))
