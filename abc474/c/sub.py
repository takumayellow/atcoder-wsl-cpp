# 【結論: 2箇所で壊れている】
#   どちらも原因は同じ ―― 「同じ x が複数回クエリされ得る」ことを見落としている。
#
#   (A) 実行時エラー (RuntimeError / ValueError)
#       1回目の x で p から抜いたあと、p に x を戻していない。
#       そのため2回目の同じ x で p.remove(x) が
#           ValueError: list.remove(x): x not in list
#       を投げてクラッシュする。
#       再現: 入力  4 3 / 4 2 3 1 / 4 / 1 / 1   → sub.py:7 で例外（実測確認済み）
#
#   (B) 仮に例外を回避しても、答えが合わない
#       l にはクエリが来た回数だけ x が積まれるので、同じ人が列に2個並ぶ。
#       正しくは「最後に呼ばれた1回だけ」が最後尾に来るべき。
#       つまり l は「集合として持ち、再登場したら古い方を消す」必要がある。
