# =============================================================================
# ABC474 C  ―  本命（O(N+Q)。実測 0.32 秒 / main.py は 9.43 秒）
# =============================================================================
#
# 【遅さの正体をどう潰すか】
#   main.py が遅い原因は list.remove() の2つの O(N) だった:
#       (1) 「x はどこにいる？」を先頭から線形探索する
#       (2) 抜いた穴を埋めるため、後ろの要素を全部前へ詰める（memmove）
#   この解法は、その2つをそれぞれ次の道具で潰す。
#       (1) → 逆引き配列 inv     : inv[x-1] = 「x が今いる配列上の位置」を O(1) で引く
#       (2) → 論理削除（墓石法） : 詰めない。抜けた場所には 0 を置いて「無効」と記す
#
# 【なぜ詰めなくていいのか】
#   この問題の移動先は「常に最後尾」に固定されている。
#   だから席を詰めて場所を再利用する必要が無く、新しい席を末尾に足し続ければよい。
#   席は使い捨てになるので、配列の長さは最大 N+Q まで伸びる（メモリ O(N+Q)）。
#   最後に墓石(0)を読み飛ばせば、生き残った要素が左から正しい順で並んでいる。
#
# 【0 を墓石に使ってよい理由】
#   P の値は 1..N の順列なので 0 は絶対に現れない。よって 0 は「空席」を表す
#   番兵として安全に使える。（値に 0 が来る問題では None や -1 を使うこと）
#
# 【計算量】 時間 O(N+Q) / メモリ O(N+Q)
# 【別解】 双方向連結リストなら メモリ O(N) で同じ O(N+Q)。
#         任意位置への移動に拡張したくなったらそちらが必要になる。
#         Python なら OrderedDict.move_to_end(x) がまさにそれ（中身が連結リスト）。
# =============================================================================

# N（人数）と Q（クエリ数）
N, Q = list(map(int, input().split()))

# 初期の並び。P[i] = 「位置 i に居る人の番号」（i は 0-indexed、P[0] が先頭）
# この配列はこの後 append で最大 N+Q まで伸びる。
P = list(map(int, input().split()))

# --- 逆引き表 inv --------------------------------------------------------------
# inv[v-1] = 「人 (v) が今いる P 上の位置」   … P とはちょうど逆向きの対応
#   人の番号 v は 1..N なので、配列添字に使うため -1 して 0..N-1 に直している。
#   （inv は伸ばさない。人数は N 人のまま増えないので長さ N で足りる。）
inv = [0] * N
for i in range(N):
    inv[P[i] - 1] = i          # 位置 i に居るのは人 P[i] → その人の現住所は i

# --- クエリ処理 -----------------------------------------------------------------
# ループ変数 i を range(N, N+Q) にしているのがミソ。
#   このあと P.append(x) をすると、その要素の位置はちょうど len(P) になる。
#   1回目の append 前の len(P) は N、2回目は N+1、… なので
#   「今回 append した要素の位置 = i」が常に成り立つ。
#   → append の戻り値が無い Python でも、新しい位置を計算せずに i で参照できる。
for i in range(N, N + Q):
    # 移動対象の人 x
    x = int(input())

    # (a) 末尾に新しい席を作って x を座らせる。位置は i。
    P.append(x)

    # (b) 元いた席を墓石(0)にする。＝ 論理削除。
    #     inv[x-1] が「移動前の位置」であることが重要。
    #     この2行の順序は (a)→(b) でも (b)→(a) でも結果は同じ
    #     （新しい席の位置 i と古い位置は必ず別なので互いに潰し合わない）。
    P[inv[x - 1]] = 0

    # (c) 現住所を新しい席 i に更新する。
    #     これを忘れると、次に同じ x が来たとき古い（既に 0 の）位置を潰しに行き、
    #     x が配列に2個残ってしまう。同じ人が複数回クエリされる入力で必ず壊れる。
    inv[x - 1] = i

# --- 出力 -----------------------------------------------------------------------
# P を左から走査し、墓石(0)を読み飛ばして生きている人だけを出す。
#   `if x:` は「x が 0 でないなら」の意（0 は falsy）。
#   走査順がそのまま列の順になっているのは、
#     ・削除しても要素をずらしていない（順序を壊していない）
#     ・追加は必ず末尾にしかしていない
#   の2点から。
#
# ※ この出力は「1行1個（改行区切り）」。main.py の print(*p) は空白区切りで、
#   両者は形式が食い違っている。問題文の出力形式に合わせること。
#   空白区切り1行にしたい場合は次の1行で置き換えられる:
#       print(*(x for x in P if x))
for x in P:
    if x:
        print(x)

# --- 動作トレース ----------------------------------------------------------------
#   入力: N=4, Q=3, P=[4,2,3,1], クエリ 4, 1, 1
#
#   初期      P=[4,2,3,1]              inv=[3,1,2,0]  (人1は位置3, 人2は位置1, ...)
#   i=4 x=4   append → [4,2,3,1,4]
#             P[inv[3]=0]=0 → [0,2,3,1,4]            inv[3]=4
#   i=5 x=1   append → [0,2,3,1,4,1]
#             P[inv[0]=3]=0 → [0,2,3,0,4,1]          inv[0]=5
#   i=6 x=1   append → [0,2,3,0,4,1,1]
#             P[inv[0]=5]=0 → [0,2,3,0,4,0,1]        inv[0]=6
#   出力      0 を飛ばして  2, 3, 4, 1   ← main.py の出力と一致
