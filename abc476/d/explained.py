#
# 【問題の要点】
#   - 紙幣は「1 ドル紙幣」と「K ドル紙幣」の 2 種類。手持ちは 1 ドル X 枚、K ドル Y 枚。
#   - デザート（N 個, 価格 A_i）: どちらの紙幣でも払える。
#   - ドリンク（M 個, 価格 B_j）: K ドル紙幣でしか払えない。
#   - お釣りは 1 ドル紙幣で返ってくる。
#   - 買える商品数の最大値を求める。
#
# 【方針】
#   ドリンクを何本買うか（t 本）を 0, 1, 2, ... と全部試す。
#   t を決めたら「ドリンクは安い順に t 本」「残金でデザートを安い順に買えるだけ」が最適。
#   各 t について、デザートの本数は累積和 + 二分探索で O(log N) で求まる。
#   全体で O(N log N + M log M)。

# 【文法メモ】
#   ・bisect_right(a, x)  昇順リスト a に x を挿入できる右端の位置を返す。
#                         x と等しい要素があればその「後ろ」を指すので、
#                         戻り値はそのまま「x 以下の要素数」になる。
#                         左端が欲しいときは bisect_left（x 未満の個数）。
#   ・accumulate(it)      先頭からの累積を順に返すイテレータ。list() で確定させる。
#                         第 2 引数 func で + 以外（operator.mul など）にもできる。
#   ・-> None / : int     型ヒント。実行時には無視され、速度にも動作にも影響しない。
#                         読み手と型チェッカ（mypy 等）のための注釈。
#   ・def の入れ子         下の max_desserts は main の中で定義されたローカル関数。
#                         引数に取っていない k や dessert_prefix を参照できるのは、
#                         外側のスコープの変数を閉じ込めた（クロージャになった）ため。
#   ・main() に包む理由    Python ではローカル変数の参照がグローバルより速いので、
#                         競プロでは処理を関数の中に入れるのが定石。

from bisect import bisect_right
from itertools import accumulate


def main() -> None:
    n, m, k = map(int, input().split())
    x, y = map(int, input().split())  # x: 1 ドル紙幣の枚数, y: K ドル紙幣の枚数
    a = list(map(int, input().split()))  # デザートの価格
    b = list(map(int, input().split()))  # ドリンクの価格

    # ---- デザート側の前処理 -------------------------------------------------
    # 安い順に並べて累積和を取る。
    #   dessert_prefix[i] = 安いデザート (i+1) 個の合計金額
    # 予算 budget のとき買えるデザートの個数は
    #   「dessert_prefix の中で budget 以下の要素の個数」= bisect_right(dessert_prefix, budget)
    # （累積和は単調増加なので二分探索が使える）
    dessert_prefix = list(accumulate(sorted(a)))

    # デザートはどちらの紙幣でも払えて、お釣りも返ってくるので、
    # 「持っているお金の総額 x + k*y 以下なら買える」と考えてよい。
    def max_desserts(one_bills: int, k_bills: int) -> int:
        budget = one_bills + k * k_bills
        return bisect_right(dessert_prefix, budget)

    # ---- ドリンク 0 本の場合 -------------------------------------------------
    # 全財産をデザートに使う。
    best = max_desserts(x, y)

    # ---- ドリンクを安い順に 1 本ずつ買い足していく -----------------------------
    drinks = 0  # ここまでに買ったドリンクの本数
    for price in sorted(b):
        # 価格 price のドリンクには K ドル紙幣が ceil(price / k) 枚必要。
        #   -(-price // k) は整数だけで ceil を計算する定番の書き方
        #   （math.ceil(price / k) は浮動小数点誤差が出うるので避ける）。
        need = -(-price // k)
        if need > y:
            # K ドル紙幣が足りない。以降のドリンクはもっと高い（=必要枚数も同じか多い）
            # ので、もう 1 本も買えない。ここで打ち切ってよい。
            break

        # K ドル紙幣 need 枚で払い、お釣り need*k - price を 1 ドル紙幣で受け取る。
        y -= need
        x += need * k - price
        drinks += 1

        # ドリンク drinks 本 + 残りのお金で買えるだけのデザート、で候補を更新。
        best = max(best, drinks + max_desserts(x, y))

    print(best)


# 【なぜこの貪欲で正しいのか】
#
# (1) ドリンクを t 本買うなら「安い順に t 本」でよい理由
#     ドリンクを 1 本買うと、K ドル紙幣が ceil(B/K) 枚減り、お釣りを含めた
#     「所持金の総額」はちょうど B だけ減る。
#     安いドリンクを選ぶほど、
#       - 必要な K ドル紙幣の枚数 ceil(B/K) は少ない（B について単調）
#       - 所持金の総額の減り B も少ない
#     ので、どちらの観点でも高いドリンクに置き換えて得することはない。
#
# (2) 先にドリンクを全部買ってからデザートを買ってよい理由
#     ドリンクには K ドル紙幣しか使えないので、K ドル紙幣は温存したい。
#     先にドリンクを買えば K ドル紙幣を確実にドリンクに回せる。
#     一方デザートは総額さえ足りれば払えるので、後回しにしても損はしない。
#
# (3) デザートを「安い順に買えるだけ」買うのは、個数を最大化する典型的な貪欲。
#
# 【具体例: サンプル 1】 K=10, X=50, Y=6, A=[22,30], B=[20,12,24]
#   デザート累積和 = [22, 52]
#   t=0: 総額 50+60=110 → デザート 2 個          → 合計 2
#   t=1: B=12, 紙幣 2 枚, お釣り 8 → X=58, Y=4
#        総額 58+40=98 → デザート 2 個           → 合計 3
#   t=2: B=20, 紙幣 2 枚, お釣り 0 → X=58, Y=2
#        総額 58+20=78 → デザート 2 個           → 合計 4  ← 最大
#   t=3: B=24, 紙幣 3 枚必要 > Y=2 → 打ち切り
#   答え 4

# 【この if の意味】
#   __name__ は、直接実行されたファイルでは "__main__"、import されたときは
#   モジュール名になる。この条件を挟んでおくと、他のファイルから import しても
#   main() が勝手に走らない（入力待ちで固まらない）。
if __name__ == "__main__":
    main()
