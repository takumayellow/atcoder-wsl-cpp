# ABC476 D - Automat（ドリンクの本数を全探索する版。explained.py と同じ方針）
#
# ドリンクを安い順に 0, 1, 2, ... 本買う場合をすべて試し、
# 各ケースで「残った総額で買えるデザートの個数」を累積和 + 二分探索で求める。
# 商品を 1 つの袋にまとめてしまう main.cpp とは別ルートだが、答えは一致する。
# 計算量 O(N log N + M log M)。

# 【from ... import ...】モジュールの中の名前だけを直接取り込む。
#   import bisect と書いた場合は bisect.bisect(...) と呼ぶことになる。
#   bisect(a, x) は「昇順の a に x を挿入できる右端の位置」を返す = a 以下の要素数。
#   同じ値があるとき左端を返すのが bisect_left、右端が bisect（= bisect_right）。
from bisect import bisect

# 【多重代入とアンパック】map が返すイテレータを 3 つの変数へ展開する。
#   右辺の要素数と左辺の変数の数が一致しないと ValueError になる。
n, m, k = map(int,input().split())
x, y = map(int,input().split())
a = list(map(int,input().split()))
b = list(map(int,input().split()))

# デザートを安い順に並べた累積和 aa（aa[i] = 安い方から i+1 個の合計金額）。
# 単調増加なので「予算以下の要素数」= 買える個数 を二分探索で取り出せる。
#
# 【.sort() は破壊的】戻り値は None。a = a.sort() と書くと a が None になる典型的なバグ。
a.sort()
aa = [0]
# 【ループ変数がリストと同名】for a in a: は「a というリストを走査しつつ、
#   a を各要素（int）に束縛し直す」という書き方。イテレータは元のリストオブジェクトを
#   掴んだままなので走査自体は最後まで正しく動くが、ループを抜けた後の a は
#   リストではなく最後の要素（int）になっている。ここでは以降 a を使わないので成立する。
#   読みづらいので、普通は for v in a: と別名にする。
for a in a:
    aa.append(aa[-1]+a)     # aa[-1] は末尾要素（負のインデックス）
aa=aa[1:]                   # 先頭に置いた番兵の 0 を落とす（スライスで新しいリストを作る）

# 先頭にダミーの 0 を置くことで、ループ 1 週目が「ドリンク 0 本」の場合になる。
# [0] + b はリストの連結で、新しいリストを作る（b 自身は変わらない）。
b.sort()
b = [0] + b

ans = 0
r = len(aa)         # 買えるデザートの個数（ドリンクを買うほど単調に減るので探索上限に使う）
s = x + y * k       # 所持金の総額。買い物のたびに価格ぶんだけ減る
# 【range(len(b))】0 から len(b)-1 まで。ib はそのまま「買ったドリンクの本数」になる
#   （b の先頭がダミーの 0 なので、ib 本目まで見た時点で実物は ib 本）。
for ib in range(len(b)):
    # 【// は切り捨て除算】(b+k-1)//k で ceil(b/k)。float を経由しないので誤差が出ない。
    #   Python の int は多倍長なので、C++ と違いオーバーフローを気にしなくてよい。
    yi = (b[ib] + k -1) // k    # このドリンクに必要な K ドル札の枚数
    if yi > y:
        # K ドル札が足りない。b は昇順なので以降はさらに買えない → 打ち切り
        break
    y -= yi
    s -= b[ib]
    # 【bisect(a, x, lo, hi)】探索範囲を [lo, hi) に限定できる。
    #   上限に r を渡しているのがポイント。r は減る一方なので、探索範囲が広がらない。
    r = bisect(aa, s, 0, r)
    ans = max(ans, r+ib)        # ドリンク ib 本 + デザート r 個

print(ans)
