# 【方針】
#   ドリンクを安い順に 0, 1, 2, ... 本買う場合を全部試す。
#     a  : デザートを安い順に並べた累積和（bisect で「予算以下の個数」を引く）
#     t  : ここまでに買ったドリンクの本数
#     q  : ドリンク 1 本に必要な K ドル札の枚数 = ceil(v/k)
#     x + k*y : 所持金の総額。ドリンクを買うとちょうど v だけ減る（お釣りは 1 ドル札）
#   先頭の [0] はダミーで、ループ 1 週目が「ドリンク 0 本」の場合に対応する。
#   v > k*y は ceil(v/k) > y と同値で、K ドル札が足りないことを意味する。
#
# 【使われている短縮テクニック】
#   ・from bisect import *   … モジュール内の公開名を全部取り込むワイルドカードインポート。
#                              bisect. の修飾が要らなくなる。名前が衝突しうるので通常は非推奨。
#   ・open(0)                … 0 はファイルディスクリプタ（標準入力）。
#                              ファイルオブジェクトは行のイテレータなので、for o in open(0) で
#                              1 行ずつ回せる。input() を 4 回呼ぶより短く、速い。
#   ・(n, m, k), (x, y), a, b = [...]
#                            … 入れ子のアンパック代入。右辺は「4 行ぶんの map」のリストで、
#                              1・2 行目はさらに 3 個 / 2 個へ展開する。
#                              a と b は map オブジェクトのまま（リスト化していない）。
#                              ※ 入力末尾に余分な空行があると要素数が合わず ValueError になる。
#   ・S = sorted             … 関数もオブジェクトなので別名を束縛できる。S(a) = sorted(a)。
#   ・z = t = s = 0          … 連鎖代入。3 つとも同じ値で初期化する。
#   ・;                      … 単純文を 1 行に並べる区切り。
#   ・[s := s + v for v in ...]
#                            … セイウチ演算子（代入式, Python 3.8+）。s を更新しながら
#                              その値を式の値として使うことで、累積和を内包表記 1 つで作る。
#                              内包表記は独自スコープを持つが、:= の束縛先は外側のスコープ
#                              （ここではモジュール直下の s）になる。
#   ・-(-v//k)               … // は床除算（負の無限大方向へ切り捨て）なので、
#                              符号を 2 回反転させると切り上げになる = ceil(v/k)。
#                              (v+k-1)//k と同じ結果で、こちらの方が短い。

from bisect import*
(n, m, k), (x, y), a, b = [map(int, o.split()) for o in open(0)]
S = sorted;z=t=s=0;a=[s:=s+v for v in S(a)]
for v in[0]+S(b):
    if v>k*y:break
    q=-(-v//k);y-=q;x+=q*k-v;z=max(z,t+bisect(a,x+k*y));t+=1
print(z)
