// ============================================================================
// ABC476 C - 3rd Largest
// ============================================================================
//
// 【問題】
//   長さ N の正整数列 A = (A_1, ..., A_N) が与えられる。
//   k = 3, 4, ..., N のそれぞれについて、A_1, ..., A_k を降順に並べたとき
//   前から 3 番目にくる値を出力する（全部で N-2 行）。
//
// 【制約】
//   3 <= N <= 5e5,  1 <= A_i <= 1e9,  入力は全て整数
//
// ----------------------------------------------------------------------------
// 【考え方】
//
//   素朴にやると、k ごとに A_1..A_k を丸ごとソートして 3 番目を見る:
//       O(N^2 log N) → N = 5e5 では到底間に合わない（simple.py がこれ）。
//
//   だが k 番目の答えに効くのは「これまでの上位 3 個」だけで、4 位以下は
//   今後どう伸ばしても 3 位以内に返り咲かない（要素は増える一方で減らない）。
//   → 上位 3 個だけを持ち歩き、新しい A_i が来たら 4 個にしてから最小を捨てる。
//     1 ステップ O(1)（4 要素のソートなので実質定数）、全体 O(N)。
//
//   ※「降順に並べて 3 番目」は多重集合としての 3 番目で、重複を潰さない。
//     例: 1 1 1 → 答えは 1。よって上位 3 個も重複込みで保持する
//     （set で持つと値が潰れて誤答になる）。
//
// 【番兵としての 0】
//   d を 0 三つで初期化しておくと、先頭の 3 要素も「押し出し」の処理だけで
//   扱えて場合分けが要らない。A_i >= 1 という制約のおかげで、0 は実データが
//   来れば必ず最小として捨てられ、答えに混ざることはない。
//   （A_i に 0 や負数を許す問題へ流用するときは、この初期値が壊れる点に注意。）
// ============================================================================

// 【#include】
//   プリプロセッサ指令。指定したヘッダの中身をこの位置へ展開する。
//   <bits/stdc++.h> は GCC の内部ヘッダで、標準ライブラリをまとめて読み込む。
//   標準規格には無いので clang/MSVC では通らないことがあり、コンパイルも遅い。
//   競プロでは「書き忘れ事故が無い」ので定番だが、業務コードでは使わない。
#include <bits/stdc++.h>

// 【using ディレクティブ】
//   std 名前空間の名前を、修飾なし（sort / vector / cin）で書けるようにする。
//   ヘッダに書くと利用側の名前と衝突するため嫌われるが、単一ファイルの競プロでは定番。
using namespace std;

// 【関数形式マクロ】
//   コンパイル前のテキスト置換。rep(i, n) は for (int i = 0; i < (n); ++i) になる。
//   ・n を (n) と括弧で囲むのが必須。囲まないと rep(i, flag ? 3 : 5) が
//     i < flag ? 3 : 5 すなわち (i < flag) ? 3 : 5 と解釈されて終了条件が壊れる
//     （実測: 括弧なしだと無限ループになった）。
//   ・(n) は毎回評価されるので、n に関数呼び出しを書くとループ毎に呼ばれる。
//   ・マクロはスコープを持たず、i はループ内だけで有効な普通の for 文の変数になる。
#define rep(i,n) for (int i = 0; i < (n); ++i)

int main() {
    int n;
    // 【cin >> n】
    //   >> は istream のメンバ演算子。空白・改行を読み飛ばしてから 1 つ読み取り、
    //   n を書き換える（引数が参照で渡るので値が反映される）。
    //   戻り値は cin 自身なので cin >> a >> b と数珠つなぎに書ける。
    cin >> n;

    // 【vector<int> d(3)】
    //   丸括弧の 3 は「要素数」。値初期化されるので中身は {0, 0, 0}。
    //   波括弧で vector<int> d{3} と書くと initializer_list のコンストラクタが
    //   優先され、要素 1 個・値 3 の別物になる（実測で確認済み）。ここは丸括弧が正しい。
    //   d は「ここまでに読んだ要素の上位 3 個」を降順で保持する（初期値は番兵の 0）。
    vector<int> d(3);

    rep(i, n) {
        int a;
        cin >> a;

        // 【push_back】末尾に要素を追加し size を 1 増やす。
        //   容量が足りなければ内部で再確保（既存要素の移動）が起こるが、
        //   ここは常に 3 → 4 → 3 の往復なので実質的な再確保は起きない。
        d.push_back(a);              // 上位 3 個 + 新要素 = 4 個にする

        // 【sort(first, last)】[first, last) の半開区間を昇順に並べ替える。
        //   rbegin() は「最後の要素」を指す逆順イテレータ、rend() は「先頭の 1 つ前」。
        //   逆順イテレータで昇順に並べる = 元の並びで見ると降順、という仕掛け。
        //   比較関数 greater<int>() を渡す書き方と結果は同じ。
        sort(d.rbegin(), d.rend());  // 降順ソート（先頭が最大）

        // 【pop_back】末尾の 1 要素を削除する。戻り値は void（値は取れない）。
        //   降順なので末尾 = 4 個中の最小。
        d.pop_back();                // 上位 3 個へ戻す

        // 【operator[]】範囲チェックをしない添字アクセス（範囲外は未定義動作）。
        //   確実に 3 要素ある場面なので問題ない。チェックが要るなら d.at(2)。
        //   i は 0-indexed なので i >= 2 が k = i+1 >= 3 に対応する。
        //   '\n' は 1 文字の char、"\n" は文字列リテラル（末尾に終端 \0 が付く別物）。
        //   endl は「改行 + フラッシュ」で、毎行フラッシュすると遅くなる。
        //   最大 5e5 行出力するのでここでは '\n' を使う。
        if (i >= 2) cout << d[2] << '\n';   // d[2] = 降順 3 番目 = この k に対する答え
    }
    // main に限り return 0; は省略できるが、明示しておく流儀。
    return 0;
}
