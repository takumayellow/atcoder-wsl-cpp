# ABC476 C - 3rd Largest（Python 版。考え方の詳細は main.cpp のコメント参照）
#
# 上位 3 個だけを持ち歩き、新要素を足して降順 3 番目を答える O(N) 解法。
# ただし Python だと N = 5e5 でこのループは重く、TLE のおそれがある
# （その場合は main.cpp を提出する）。

# 【input() と map】
#   input() は標準入力から 1 行読み、末尾の改行を取り除いた文字列を返す。
#   "5" のような 1 個の値なら int() でそのまま数値にできる。
n = int(input())

# 【map(f, iterable)】各要素に f を適用するイテレータを返す（この時点ではまだ計算しない）。
#   input().split() は空白で区切った文字列のリスト ['1','2',...]。
#   list(...) で map を実際に消費してリストにする。
#   ※ map は 1 回使うと空になるので、2 回走査するならリスト化が必要。
a = list(map(int, input().split()))

# 【sorted(x) と x.sort()】
#   sorted は新しいリストを返す（元は不変）。x.sort() は破壊的に並べ替えて None を返す。
#   ここは元の a を残したいので sorted を使う。既定は昇順。
# 【スライス a[:3]】先頭 3 個の新しいリスト。要素数が 3 未満でもエラーにならない。
s = sorted(a[:3])

# 【負のインデックス】s[-1] が末尾、s[-3] は末尾から 3 番目。
#   s は昇順 3 要素なので s[-3] = s[0] = 最小 = 降順で 3 番目。
print(s[-3])

# 【range(3, n)】3, 4, ..., n-1 を生成する（終端 n は含まない）。
#   a は 0-indexed なので a[k] は「k+1 番目の要素」。
for k in range(3, n):
    s.append(a[k])   # 上位 3 個 + 新要素 = 4 個。append は末尾追加で戻り値は None
    s = sorted(s)
    # 【スライス s[-3:]】末尾 3 個を取り出した新しいリスト。
    #   先頭（= 最小）が切り捨てられ、上位 3 個が昇順のまま残る。
    s = s[-3:]
    print(s[-3])
